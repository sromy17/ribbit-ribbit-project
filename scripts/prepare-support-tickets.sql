-- Extend the existing support-ticket table without changing trades or existing tickets.
BEGIN;
ALTER TABLE support_ticket ADD COLUMN IF NOT EXISTS category VARCHAR(30) DEFAULT 'PLATFORM_QUESTION';
ALTER TABLE support_ticket ADD COLUMN IF NOT EXISTS message TEXT;
ALTER TABLE support_ticket ADD COLUMN IF NOT EXISTS request_key UUID;
ALTER TABLE support_ticket ADD COLUMN IF NOT EXISTS resolution TEXT;
ALTER TABLE support_ticket ADD COLUMN IF NOT EXISTS version INT NOT NULL DEFAULT 0;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid='support_ticket'::regclass
                 AND attname='ticket_id' AND attidentity <> '') THEN
    ALTER TABLE support_ticket ALTER COLUMN ticket_id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END $$;
SELECT setval(pg_get_serial_sequence('support_ticket','ticket_id'),
              greatest(coalesce(max(ticket_id),0)+1,1),false) FROM support_ticket;
CREATE UNIQUE INDEX IF NOT EXISTS support_ticket_request_key_idx ON support_ticket(request_key);
CREATE INDEX IF NOT EXISTS support_ticket_account_created_idx ON support_ticket(accountid,created_at DESC,ticket_id DESC);
COMMIT;
